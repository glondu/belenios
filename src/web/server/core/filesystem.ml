open Lwt.Syntax
open Belenios
include Belenios_spool.Files

let read_file_i18n ~lang f =
  let* f =
    let f' = Printf.sprintf "%s.%s" f (Language.unwrap lang) in
    let* b = file_exists f' in
    Lwt.return (if b then f' else f)
  in
  read_file f
